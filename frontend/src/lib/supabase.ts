import { createClient, type SupabaseClient } from "@supabase/supabase-js";

const url = import.meta.env.VITE_SUPABASE_URL;
const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

/** True when Supabase env is configured. Lets the UI show a helpful message otherwise. */
export const isSupabaseConfigured = Boolean(url && anonKey);

// A single shared client. Session is persisted to localStorage and auto-refreshed by
// supabase-js, giving us login persistence across reloads for free.
export const supabase: SupabaseClient = createClient(
  url ?? "https://placeholder.supabase.co",
  anonKey ?? "placeholder-anon-key",
  {
    auth: {
      persistSession: true,
      autoRefreshToken: true,
      detectSessionInUrl: true,
    },
  },
);
